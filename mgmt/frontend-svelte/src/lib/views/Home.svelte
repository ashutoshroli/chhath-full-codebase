<script lang="ts">
  // Ported from React views/Home.jsx — budget overview + collections list for a
  // year: add/edit/delete COLLECTIONS, contributor history, auto doc generation
  // (receipt/certificate/samaan) enqueued to the background queue, resell entries.
  import { api, fmt, reportClientError } from '$lib/api';
  import { createViewData, type ViewData } from '$lib/viewData';
  import { invalidate } from '$lib/cache';
  import Modal from '$lib/components/Modal.svelte';
  import SearchableSelect from '$lib/components/SearchableSelect.svelte';
  import QuickAddUser from '$lib/components/QuickAddUser.svelte';
  import RowActions from '$lib/components/RowActions.svelte';
  import QueueStatus from '$lib/components/QueueStatus.svelte';
  import { canAddView } from '$lib/permissions';
  import { createDropdownList } from '$lib/dropdownList';
  import { isTruthyFlag } from '$lib/flags';
  import { checkMoney } from '$lib/money';
  import { personOptions } from '$lib/personOption';
  import { newUid } from '$lib/a11y/uid';
  // audit PR-40: one prefix per instance, so `for`/`id` pairs cannot collide when a
  // component is mounted more than once on a screen.
  const uid = newUid();

  interface Props {
    year: string;
    users: any[];
    onUserCreated: () => void;
    role: string;
    editable: boolean;
  }
  let { year, users, onUserCreated, role, editable }: Props = $props();

  function autoGenerateDocType(payload: any): string | null {
    if (payload['Is Resell'] === 'TRUE') return null;
    const type = payload['Contribution Type'];
    if (type === '1') return 'receipt';
    if (type === '2') return 'samaan';
    if (type === '3') return payload['Certificate Or Receipt'] === 'Certificate' ? 'certificate' : 'receipt_work';
    return null;
  }

  const RENDER_CAP = 300;
  const BLANK = () => ({
    Name: '', Amount: '', 'Payment Mode': 'Cash', UTR: '',
    Date: new Date().toISOString().slice(0, 10), 'Contribution Type': '1',
    Detail: '', 'Certificate Or Receipt': 'Receipt', 'Is Resell': false
  });

  // Year-scoped home view.
  // audit PR-40: deliberate one-time capture. This is EDITABLE local state seeded from a
  // prop; making it `$derived` would discard whatever the operator has typed every time the
  // parent re-rendered. The prop is re-read where it genuinely needs to be (see the $effect).
  // svelte-ignore state_referenced_locally
  let view = $state<ViewData<any>>(createViewData(`home:${year}`, () => api.getHome(year)));
  // audit PR-40: deliberate one-time capture. This is EDITABLE local state seeded from a
  // prop; making it `$derived` would discard whatever the operator has typed every time the
  // parent re-rendered. The prop is re-read where it genuinely needs to be (see the $effect).
  // svelte-ignore state_referenced_locally
  let lastYear = year;
  $effect(() => {
    if (year !== lastYear) {
      lastYear = year;
      view = createViewData(`home:${year}`, () => api.getHome(year));
    }
  });
  let vs = $state({ data: undefined as any, loading: true, error: '' });
  $effect(() => view.subscribe((v) => (vs = v as any)));

  const paymentModeList = createDropdownList('Payment Mode');
  let paymentModeOptions = $state<any[]>([]);
  $effect(() => paymentModeList.subscribe((s) => (paymentModeOptions = s.options)));
  const paymentModeHindiOf = (v: string) => paymentModeList.hindiOf(v);

  let search = $state('');
  let showAdd = $state(false);
  let showQuickAdd = $state(false);
  let form = $state<any>(BLANK());
  let saving = $state(false);
  let savingStep = $state('');
  let postSaveWarning = $state('');
  let queueBump = $state(0);
  let editing = $state<any>(null);
  let history = $state<any[] | null>(null);
  let historyLoading = $state(false);

  let userMap = $derived.by(() => {
    const m: Record<string, any> = {};
    (users || []).forEach((u) => (m[u.ID] = u));
    return m;
  });
  // Name + father's name, so two same-name people in one village are distinguishable — and
  // searchable by either (see lib/personOption.ts).
  let userOptions = $derived(personOptions(users));

  // Contribution history for the selected contributor (matches deps [form.Name]).
  let lastHistName = '__init__';
  $effect(() => {
    const name = form.Name;
    if (name === lastHistName) return;
    lastHistName = name;
    if (!name) { history = null; return; }
    historyLoading = true;
    api.getUserHistory(name)
      .then((h: any) => (history = h))
      .catch(() => (history = null))
      .finally(() => (historyLoading = false));
  });

  let filtered = $derived.by(() => {
    const q = search.toLowerCase();
    return (vs.data?.collections || []).filter((r: any) => {
      if (isTruthyFlag(r['Is Resell'])) return (r.Detail || '').toLowerCase().includes(q);
      const u = userMap[r.Name] || { Name: 'Unknown User' };
      return (u.Name || '').toLowerCase().includes(q);
    });
  });
  let visible = $derived(filtered.slice(0, RENDER_CAP));

  // FEAT-003: the browser no longer fills the .docx or builds the QR for the auto
  // path — that moved server-side (Render). The old fillDocxForQueue (which imported
  // $lib/docxFill + $lib/qrCode and called getDocxTemplateForDoc / getReceiptData) is
  // gone, so this bundle no longer pulls docxtemplater/qrcode for the auto path.

  async function submit(e: Event) {
    e.preventDefault();
    const isMoney = form['Contribution Type'] === '1';
    const isResell = isMoney && !!form['Is Resell'];
    const isUtrMode = isMoney && !isResell && (form['Payment Mode'] === 'UPI' || form['Payment Mode'] === 'Online');
    if (isResell) {
      if (!form.Detail.trim()) { alert("Resold item's name is required"); return; }
    } else {
      if (!form.Name) { alert('Please select a contributor'); return; }
      if (!isMoney && !form.Detail.trim()) { alert('Detail is required (what was given / what work was done)'); return; }
    }
    // audit P0-09: this used to be `if (!form.Amount)` only, so -500 / 1e21 /
    // '12.3456' were sent to the API. Same rules as the backend (lib/money.ts).
    if (isMoney || isResell) {
      const amount = checkMoney(form.Amount, 'Amount');
      if (!amount.ok) { alert(amount.message); return; }
    }
    saving = true;
    try {
      const payload: any = {
        Name: isResell ? '' : form.Name,
        'Payment Mode': isMoney ? form['Payment Mode'] : '',
        UTR: isUtrMode ? form.UTR : '',
        Date: form.Date,
        'Contribution Type': form['Contribution Type'],
        Amount: (isMoney || isResell) ? form.Amount : '',
        Detail: (isMoney && !isResell) ? '' : form.Detail,
        'Certificate Or Receipt': form['Contribution Type'] === '3' ? form['Certificate Or Receipt'] : '',
        'Is Resell': isResell ? 'TRUE' : 'FALSE'
      };
      let savedRowIndex: number;
      let genYear: any;
      const isNewEntry = !editing;
      if (editing) {
        genYear = editing.Year;
        savedRowIndex = editing.__rowIndex;
        // `Sl. No.` and `Created By` are NOT sent. The server owns both — the receipt
        // number and who recorded the entry — and since #323 it REJECTS them, which is
        // what broke every edit on this screen. Leaving them out is safe as well as
        // required: updateRecord builds `SET` from the keys it receives, so a column that
        // is not sent keeps its stored value.
        await api.updateRecord('COLLECTIONS', editing.__rowIndex, { Year: editing.Year, ...payload });
      } else {
        genYear = year === 'All' ? new Date().getFullYear() : year;
        const res: any = await api.saveRecord('COLLECTIONS', { Year: genYear, ...payload });
        savedRowIndex = res.rowIndex;
      }
      invalidate('home:');

      const docType = autoGenerateDocType(payload);
      const warnings: string[] = [];

      // FEAT-003: enqueue REFERENCES ONLY. The server derives the recordId +
      // payload from the stored row (audit P0-03), resolves the template,
      // dispatches the fill + QR + PDF to Render, and on the callback writes the
      // index and sends WhatsApp then email in that order.
      savingStep = 'Adding to the queue...';
      try {
        await api.enqueueCollectionJob({
          docType: docType || '',
          year: genYear,
          rowIndex: savedRowIndex,
          isNewEntry
        });
        api.processCollectionQueue().catch(() => {});
        warnings.push('The document and WhatsApp message have been queued in the background — they will complete shortly.');
      } catch (err) {
        reportClientError('Home', 'enqueueCollectionJob failed', err as Error, { docType, genYear, rowIndex: savedRowIndex });
        // The entry was saved; only the background queue failed. There is no
        // in-browser fallback any more (the fill is server-side) — surface it so
        // the operator can retry from the Queue Monitor.
        warnings.push('The entry was saved, but queuing the document/message failed: ' + (err as Error).message
          + ' A Superadmin can retry it from the Queue Monitor.');
      }

      postSaveWarning = warnings.join(' | ');
      queueBump = queueBump + 1;
      closeModal();
      view.refresh();
    } catch (err) {
      alert((err as Error).message);
    } finally {
      saving = false;
      savingStep = '';
    }
  }

  function closeModal() {
    showAdd = false;
    editing = null;
    form = BLANK();
  }

  function openEdit(r: any) {
    editing = r;
    form = {
      Name: r.Name, Amount: r.Amount, 'Payment Mode': r['Payment Mode'] || 'Cash', UTR: r.UTR || '',
      Date: r.Date || new Date().toISOString().slice(0, 10),
      'Contribution Type': (r['Contribution Type'] ?? '').toString() || '1', Detail: r.Detail || '',
      'Certificate Or Receipt': r['Certificate Or Receipt'] || 'Receipt',
      'Is Resell': r['Is Resell'] === 'TRUE' || r['Is Resell'] === true
    };
    showAdd = true;
  }

  async function remove(r: any) {
    if (!confirm('Delete this collection entry?')) return;
    try {
      await api.deleteRecord('COLLECTIONS', r.__rowIndex);
      invalidate('home:');
      view.refresh();
    } catch (err) {
      alert((err as Error).message);
    }
  }

  function historyTags(h: any): string[] {
    const tags: string[] = [];
    if (h.HasSamaan) tags.push('Material');
    if (h.HasKaam) tags.push('Service');
    return tags;
  }
</script>

{#if vs.loading}
  <div class="inline-spinner">Loading budget...</div>
{:else if vs.error}
  <div role="alert" class="error-banner">{vs.error}</div>
{:else if !vs.data}
  <div class="inline-spinner">Loading budget...</div>
{:else}
  {@const data = vs.data}
  <div class="glass-card budget-card">
