export function normalizeLang(v: unknown): Lang {
  return v === 'hi' ? 'hi' : 'en';
}

/** Translate a key with optional {placeholder} interpolation. Falls back en -> key. */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = (T[lang] && T[lang][key]) ?? T.en[key] ?? key;
  if (vars) {
    for (const [k, val] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(val));
    }
  }
  return s;
}

/** Prefer the "<field> (Hindi)" column when hi; fall back to the English column. */
export function localize(
  row: Record<string, unknown> | null | undefined,
  field: string,
  lang: Lang
): string {
  if (!row) return '';
  const enVal = row[field];
  const en = enVal === undefined || enVal === null ? '' : String(enVal);
  if (lang !== 'hi') return en;
  const hiVal = row[`${field} (Hindi)`];
  const hi = hiVal === undefined || hiVal === null ? '' : String(hiVal).trim();
  return hi || en;
}
